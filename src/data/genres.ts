export const CUSTOM_GENRE_ID = 'custom';
export const CUSTOM_CARDS_STORAGE_KEY = 'imposter_custom_cards_v1';
export const PLAYER_PRESETS_STORAGE_KEY = 'imposter_player_names_v1';

export function loadCustomEntries(): WordEntry[] {
  try {
    if (typeof window === 'undefined' || !window.localStorage) return [];
    const raw = window.localStorage.getItem(CUSTOM_CARDS_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed)) return [];
    return parsed.filter(
      (item): item is WordEntry =>
        item &&
        typeof item.id === 'string' &&
        typeof item.teamWord === 'string' &&
        typeof item.imposterWord === 'string' &&
        typeof item.hint === 'string'
    );
  } catch {
    return [];
  }
}

export function saveCustomEntries(entries: WordEntry[]): void {
  try {
    if (typeof window === 'undefined' || !window.localStorage) return;
    window.localStorage.setItem(CUSTOM_CARDS_STORAGE_KEY, JSON.stringify(entries));
  } catch {
    // Ignore storage quota errors
  }
}
